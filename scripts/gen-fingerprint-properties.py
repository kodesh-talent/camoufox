#!/usr/bin/env python3
"""Generate the C++ fingerprint-property table from settings/properties.json."""

import argparse
import json
from pathlib import Path


CPP_TYPES = {
    "str": "String",
    "uint": "UnsignedInteger",
    "int": "Integer",
    "double": "Number",
    "bool": "Boolean",
    "array": "Array",
    "dict": "Object",
}


def render(properties_path: Path) -> str:
    properties = json.loads(properties_path.read_text(encoding="utf-8"))
    entries = []
    seen = set()
    for item in properties:
        name = item["property"]
        if name in seen:
            raise ValueError(f"duplicate property: {name}")
        seen.add(name)
        if not item.get("fingerprint", False):
            continue
        try:
            cpp_type = CPP_TYPES[item["type"]]
        except KeyError as exc:
            raise ValueError(
                f"unsupported fingerprint property type for {name}: {item.get('type')}"
            ) from exc
        entries.append(f'  X("{name}", {cpp_type})')

    if not entries:
        raise ValueError("properties.json declares no fingerprint properties")

    lines = [
        "/* Generated by scripts/gen-fingerprint-properties.py. */",
        "#define CAMOUFOX_FINGERPRINT_PROPERTIES(X) \\",
    ]
    for index, entry in enumerate(entries):
        suffix = " \\" if index + 1 < len(entries) else ""
        lines.append(entry + suffix)
    lines.append("")
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("properties", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    content = render(args.properties)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(content, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
